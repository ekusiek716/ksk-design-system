/**
 * CSS ファイルには P049（product theme の許可リスト検査）と P050（並行パレット検出、
 * issue #393）だけを当てる。TSX 向けの正規表現ルールを CSS に流すと誤検知しかしない。
 */
function lintCssFile(file, cwd, cssRules, contract, dsCssIdentity = null, pkgRoot = null) {
  const rel = normalize(relative(cwd, file))
  const isDsFile = isDsPackageFile(file, pkgRoot)
  const source = readFileSync(file, "utf8")
  // 自動生成 CSS（source-safelist.css 等）は生成元を直すべきなので全ルール skip（issue #408）
  if (isAutoGeneratedSource(source)) return []
  // DS 自身 / ベンダリングされた DS のトークン定義 CSS は「上書き」ではない（issue #407）
  if (isDsOwnCss(file, source, dsCssIdentity)) return []
  const escape = findEscape(source, rel)
  if (escape.valid) return []

  const ignores = collectRuleIgnores(source, rel)
  const findings = escape.invalid ? [escape.invalid] : []
  findings.push(...ignores.problems)
  for (const rule of cssRules) {
    // CSS は web のみに存在する（RN に .css は無い）。glob 指定の appliesTo は
    // capability タグを含まないので、この判定でも従来どおり P049/P050 が当たる。
    if (!ruleAppliesTo(rule, { capabilities: CSS_CAPABILITIES, filePath: rel })) continue

    if (rule.engine === "parallel-palette") {
      // contract が読めない（DS の名前空間一覧が無い）と何が DS 名前空間かを
      // 判定できず false positive しか出せないので、その場合は skip する。
      if (!contract) continue
      const threshold = typeof rule.minColorVars === "number" ? rule.minColorVars : 5
      const candidates = inspectParallelPaletteCandidates(source, { namespaces: contract.namespaces })
      if (candidates.length < threshold) continue
      const first = candidates[0]
      if (matchesRuleExclude(rule, { file: rel, line: first.name, isDsFile })) continue
      if (ignores.suppresses(rule.id ?? "UNKNOWN", first.line)) continue
      const names = candidates.slice(0, 5).map((c) => c.name).join(", ")
      const suffix = candidates.length > 5 ? ` ほか計${candidates.length}個` : `（計${candidates.length}個）`
      findings.push({
        ...toFinding(rule, rel, first.line, "web"),
        message: `${rule.message ?? "DS を参照しない並行パレットの疑い"}: ${names}${suffix}`,
      })
      continue
    }

    // contract が読めない環境（contracts/product-theme-overrides.json が無い）では
    // P049 の許可リスト判定ができないので skip する（従来は呼び出し元で丸ごと
    // skip していたのと同じ挙動を、CSS ルール単位に落とし込んだだけ）。
    if (!contract) continue
    for (const violation of inspectProductThemeOverrides(source, contract)) {
      // violation.name は CSS 変数名（＝内容）なので line 側に渡す。
      // パス除外を変数名に当ててはいけない（issue #404 の提案 c）。
      if (matchesRuleExclude(rule, { file: rel, line: violation.name, isDsFile })) continue
      if (ignores.suppresses(rule.id ?? "UNKNOWN", violation.line)) continue
      findings.push({
        ...toFinding(rule, rel, violation.line, "web"),
        message: `${rule.message ?? "product theme の許可リスト外の変数を上書きしています"}: ${violation.name}`,
      })
    }
  }
  return findings
}

function lintFile(file, cwd, rules, options = {}) {
  const rel = normalize(relative(cwd, file))
  const isDsFile = isDsPackageFile(file, options.pkgRoot)
  const source = readFileSync(file, "utf8")
  // 自動生成物（src/tokens/native/themes.ts 等）は hex をそこにしか書けない。
  // 直す先は生成物ではなく生成元なので、全ルールを skip する（issue #408）。
  if (isAutoGeneratedSource(source)) return []
  const escape = findEscape(source, rel)
  if (escape.valid) return []

  const ignores = collectRuleIgnores(source, rel)
  const findings = []
  if (escape.invalid) findings.push(escape.invalid)
  findings.push(...ignores.problems)
  const lines = source.split(/\r?\n/)
  // コメント除去はファイル単位で1回だけ計算し、全ルールで使い回す
  // （ルール数 × 行数で毎回スキャンし直すコストを避ける）。
  // マスク後も文字インデックス・行番号は元の source と完全に一致する
  // （改行はそのまま残し、コメント本文だけを同じ文字数の空白に置換するため）。
  const maskedSource = maskComments(source)
  const maskedLines = maskedSource.split(/\r?\n/)
  // capability 判定に必要なマスク（コメント / 文字列 / テンプレート）は
  // detectPlatform・detectCapabilities の内側で行うので、生の source を渡す。
  // 種類ごとにマスク範囲が違うため、ここで作った maskedSource は流用できない。
  const platform = detectPlatform(rel, source, options.platform)
  const capabilities = detectCapabilities(rel, source, options.platform)

  for (const rule of rules) {
    if (!ruleAppliesTo(rule, { capabilities, filePath: rel })) continue
    if (rule.engine === "card-direct-child-spacing") {
      if (!options.inspectCardChildSpacing) continue
      for (const finding of options.inspectCardChildSpacing(source, file)) {
        const line = lines[finding.line - 1] ?? ""
        if (ignores.suppresses(rule.id ?? "UNKNOWN", finding.line)) continue
        if (!matchesRuleExclude(rule, { file: rel, line, isDsFile })) {
          findings.push(toFinding(rule, rel, finding.line, platform))
        }
      }
      continue
    }
    const isFullFileRule = rule.pattern.includes("[\\s\\S]")
    let regex
    try {
      // 全ファイル横断ルールは matchAll で複数件拾うため g フラグを必須にする
      // （issue #389: source.match() は最初の1件しか返さず取りこぼしていた）。
      regex = new RegExp(rule.pattern, isFullFileRule ? "g" : undefined)
    } catch {
      continue
    }
    if (isFullFileRule) {
      // コメントでマスク済みの source に対して照合する（issue #390 のレビュー指摘:
      // マスクが行単位の分岐にしか無いと、コメント中の <input placeholder> が
      // P026 に、SheetHeader/KebabMenu を説明する一文が P037 に誤検知していた）。
      for (const match of maskedSource.matchAll(regex)) {
        if (match.index == null) continue
        const lineNumber = lineForIndex(maskedSource, match.index)
        // excludes（ksk-ds-allow-* 等）はコメントに書かれることが多いため、
        // 判定は常にマスク前の生の行に対して行う。
        const rawLine = lines[lineNumber - 1] ?? ""
        if (matchesRuleExclude(rule, { file: rel, line: rawLine, isDsFile })) continue
        if (ignores.suppresses(rule.id ?? "UNKNOWN", lineNumber)) continue
        findings.push(toFinding(rule, rel, lineNumber, platform))
      }
      continue
    }
    for (let index = 0; index < lines.length; index++) {
      const rawLine = lines[index]
      if (matchesRuleExclude(rule, { file: rel, line: rawLine, isDsFile })) continue
      const maskedLine = maskedLines[index] ?? ""
      if (!regex.test(maskedLine)) continue
      if (rule.id === "P029" && isP029TemplateLiteralExempt(rawLine)) continue
      if (ignores.suppresses(rule.id ?? "UNKNOWN", index + 1)) continue
      findings.push(toFinding(rule, rel, index + 1, platform))
    }
  }

  return findings
}

function toFinding(rule, file, line, platform = "web") {
  return {
    file,
    line,
    ruleId: rule.id ?? "UNKNOWN",
    // 語彙は contract 側（rules.json）の "warning" に統一する（issue #406）。
    // v1.62.0 より前は JSON 出力だけ "warn" だった。
    severity: rule.severity === "error" ? "error" : "warning",
    category: rule.category ?? "pattern",
    message: rule.message ?? rule.name ?? "DS rule violation",
    // native ファイルには Web 前提の修正提案（var(--...) 等）が実行不能なので、
    // ルールが fixNative を持つならそちらを出す（issue #391）。
    fix: (platform === "native" ? rule.fixNative : null) ?? rule.fix ?? "",
  }
}

/** escape の理由として実質的な内容があるか（issue #405） */
function isMeaningfulReason(reason) {
  const trimmed = (reason ?? "").trim().replace(/[-*/\s]+$/, "").trim()
  return trimmed.length >= MIN_ESCAPE_REASON_LENGTH
}

/**
 * ファイル全体・全ルールの escape（`ksk-ds-allow-custom-ui: 理由`）。
 *
 * **文字列リテラルの中身を潰したソース**に対して探す（issue #405）。生ソースに
 * 正規表現をかけていたため `const DOC = "…/ksk-ds-allow-custom-ui: see docs"` の
 * ようなドキュメント URL でファイル全体の lint が黙って無効化されていた。
 * コメントは残すので、本来の使い方（コメントに書く）はそのまま動く。
 */
function findEscape(source, file) {
  const scanned = maskCodeStrings(source)
  const match = scanned.match(/ksk-ds-allow-custom-ui(?::\s*(.+))?/)
  if (!match) return { valid: false }
  const reason = match[1]
  if (isMeaningfulReason(reason)) return { valid: true }
  return {
    valid: false,
    invalid: {
      file,
      line: lineForIndex(scanned, match.index ?? 0),
      ruleId: "ESCAPE001",
      severity: "error",
      category: "escape",
      message: `ksk-ds-allow-custom-ui には ${MIN_ESCAPE_REASON_LENGTH} 文字以上の理由が必要です`,
      fix: "例: // ksk-ds-allow-custom-ui: medical chart requires bespoke interaction（ルール単位の // ksk-ds-lint-ignore P008 -- 理由 を推奨）",
    },
  }
}

/**
 * ルール単位・行単位の escape（issue #405）。
 * DS 内部の scripts/check-flex-shrink.mjs の `ksk-lint-ignore KFX001 -- 理由` と同型。
 *
 *   // ksk-ds-lint-ignore P008 -- ブランドロゴの規定色
 *   // ksk-ds-lint-ignore-file P008 -- ブランド定数ファイル
 *
 * 行スコープは「そのコメント行の直下 2 行以内」に効く（同一行の行末コメントも可）。
 * ファイルスコープ（`-file`）は指定ルールだけをそのファイル全体で外す。
 * どちらも理由必須で、空虚な理由は ESCAPE002 として報告し **ignore を効かせない**。
 */
const RULE_IGNORE_RE = /ksk-ds-lint-ignore(-file)?\s+([A-Za-z][A-Za-z0-9_]*)\s*(?:--\s*([^*]*))?/g

/** 行スコープ ignore が効く範囲（コメント行からの下方向の行数） */
const RULE_IGNORE_LOOKAHEAD = 2

function collectRuleIgnores(source, file) {
  const lines = maskCodeStrings(source).split(/\r?\n/)
  /** @type {Map<string, number[]>} ruleId → コメントが置かれた行番号（1始まり） */
  const scoped = new Map()
  const fileScoped = new Set()
  const problems = []

  for (let index = 0; index < lines.length; index++) {
    for (const match of lines[index].matchAll(RULE_IGNORE_RE)) {
      const isFileScope = Boolean(match[1])
      const ruleId = match[2]
      if (!isMeaningfulReason(match[3])) {
        problems.push({
          file,
          line: index + 1,
          ruleId: "ESCAPE002",
          severity: "error",
          category: "escape",
          message: `ksk-ds-lint-ignore${isFileScope ? "-file" : ""} ${ruleId} には ${MIN_ESCAPE_REASON_LENGTH} 文字以上の理由が必要です（この ignore は無効として扱いました）`,
          fix: `例: // ksk-ds-lint-ignore ${ruleId} -- ブランドロゴの規定色のため`,
        })
        continue
      }
      if (isFileScope) {
        fileScoped.add(ruleId)
        continue
      }
      const at = scoped.get(ruleId) ?? []
      at.push(index + 1)
      scoped.set(ruleId, at)
    }
  }

  return {
    problems,
    /** @param {string} ruleId @param {number} line */
    suppresses(ruleId, line) {
      if (fileScoped.has(ruleId)) return true
      const at = scoped.get(ruleId)
      if (!at) return false
      return at.some((commentLine) => line >= commentLine && line - commentLine <= RULE_IGNORE_LOOKAHEAD)
    },
  }
}

/**
 * 文字列リテラルの**中身**だけを空白へ潰し、コメントはそのまま残す（issue #405）。
 * 文字数・行番号は元の source と完全に一致する。maskComments とはちょうど逆で、
 * 「コメントに書く前提のマーカー」を安全に探すために使う。CSS にもそのまま使える。
 */
function maskCodeStrings(source) {
  let result = ""
  const n = source.length
  let i = 0

  while (i < n) {
    const ch = source[i]

    if (ch === "/" && source[i + 1] === "/") {
      while (i < n && source[i] !== "\n" && source[i] !== "\r") {
        result += source[i]
        i += 1
      }
      continue
    }

    if (ch === "/" && source[i + 1] === "*") {
      result += "/*"
      i += 2
      while (i < n && !(source[i] === "*" && source[i + 1] === "/")) {
        result += source[i]
        i += 1
      }
      if (i < n) {
        result += "*/"
        i += 2
      }
      continue
    }

    if (ch === "'" || ch === '"' || ch === "`") {
      result += ch
      i += 1
      while (i < n) {
        if (source[i] === "\\" && i + 1 < n) {
          result += blankChar(source[i]) + blankChar(source[i + 1])
          i += 2
          continue
        }
        if (source[i] === ch) {
          result += ch
          i += 1
          break
        }
        result += blankChar(source[i])
        i += 1
      }
      continue
    }

    result += ch
    i += 1
  }

  return result
}

function lineForIndex(source, index) {
  return source.slice(0, index).split(/\r?\n/).length
}

// ソース全体を1文字ずつ走査し、コメント本文だけを同じ文字数の空白に
// 置換したソースを返す（改行はそのまま残すので行番号・文字インデックスは
// 元の source と完全に一致する）。対象は // 行コメント、複数行にまたがる
// /* ... */ ブロックコメント、および JSX の単一行コメント {/* ... */}
// （中身が /* ... */ そのものなので同じ分岐で処理される）。
//
// 文字列リテラル（' " `）の内側は絶対にマスクしない。これが issue #390 の
// レビューで実証された根本原因の修正: 従来の stripLineComment は
// `indexOf("//")` で単純に切り落としていたため、
// `<img src="https://cdn.x/a.png" alt="…" />` のような URL を含む行で
// alt 以降ごと消え、alt があるのに P025 が誤検知していた。
//
// 簡易スキャナのため、テンプレートリテラル内の `${ ... }` 式に現れる
// // や /* までは追跡しない（バッククォート文字列の一部として丸ごと
// 文字列扱いにする）。同様に、JS の正規表現リテラル（/foo\/bar/）も
// 専用には解釈しない。DS の対象ファイル（JSX/TSX コンポーネント）では
// どちらも実質的に稀なため、誤検知を減らすという目的に対しては許容する。
function maskComments(source) {
  let result = ""
  let stringChar = null // 現在文字列リテラルの内側なら区切り文字（' " `）、外側なら null
  const n = source.length
  let i = 0

  while (i < n) {
    const ch = source[i]

    if (stringChar) {
      // 文字列の内側: エスケープはペアで読み飛ばし、区切り文字が来たら閉じる
      if (ch === "\\" && i + 1 < n) {
        result += ch + source[i + 1]
        i += 2
        continue
      }
      if (ch === stringChar) stringChar = null
      result += ch
      i += 1
      continue
    }

    if (ch === "'" || ch === '"' || ch === "`") {
      stringChar = ch
      result += ch
      i += 1
      continue
    }

    if (ch === "/" && source[i + 1] === "/") {
      // 行コメント: 改行の直前まで空白に置換する
      while (i < n && source[i] !== "\n" && source[i] !== "\r") {
        result += " "
        i += 1
      }
      continue
    }

    if (ch === "/" && source[i + 1] === "*") {
      // ブロックコメント（複数行対応）。JSX の {/* ... */} も外側の { } は
      // 通常のコードとして残り、中身の /* ... */ だけがここで処理される。
      while (i < n && !(source[i] === "*" && source[i + 1] === "/")) {
        result += source[i] === "\n" || source[i] === "\r" ? source[i] : " "
        i += 1
      }
      if (i < n) {
        result += "  " // 終端の */ も空白化する
        i += 2
      }
      continue
    }

    result += ch
    i += 1
  }

  return result
}

/** 文字数と行番号を保ったまま 1 文字を潰す（改行だけは残す） */
function blankChar(ch) {
  return ch === "\n" || ch === "\r" ? ch : " "
}

const ALL_STRING_DELIMITERS = new Set(["'", '"', "`"])
const TEMPLATE_DELIMITER_ONLY = new Set(["`"])

/**
 * 文字列リテラルの**中身**を同じ文字数の空白へ置換したソースを返す（issue #391）。
 * クォート記号そのものは残し、改行もそのまま残すので、文字インデックス・行番号は
 * 元の source と完全に一致する。
 *
 * `delimiters` でどの種類の文字列を潰すかを選べる。どの場合も ' " ` の 3 種すべてを
 * **追跡**する（通常文字列の中のバッククォートをテンプレート開始と誤認しないため）が、
 * 中身を潰すのは `delimiters` に含まれる区切り文字の文字列だけ。
 *
 * 既知の限界（maskComments と同じ簡易スキャナのため）:
 * - テンプレートリテラルの `${ ... }` 式の内側は追跡せず、テンプレートの一部として
 *   丸ごと文字列扱いにする
 * - JS の正規表現リテラル（/foo\/bar/）は専用に解釈しない
 * - JSX テキスト中のアポストロフィ（`<Text>don't</Text>`）は文字列開始として
 *   扱われる。この場合 className= を見落として tailwind capability が付かない側に
 *   倒れる（＝ルールを外す方向で、誤検知を増やす方向ではない）
 */
function maskStrings(source, delimiters = ALL_STRING_DELIMITERS) {
  let result = ""
  let stringChar = null
  const n = source.length
  let i = 0

  while (i < n) {
    const ch = source[i]

    if (stringChar) {
      const shouldBlank = delimiters.has(stringChar)
      // エスケープはペアで読み飛ばす（\" が文字列を閉じないように）
      if (ch === "\\" && i + 1 < n) {
        result += shouldBlank ? blankChar(ch) + blankChar(source[i + 1]) : ch + source[i + 1]
        i += 2
        continue
      }
      if (ch === stringChar) {
        stringChar = null
        result += ch
        i += 1
        continue
      }
      result += shouldBlank ? blankChar(ch) : ch
      i += 1
      continue
    }

    if (ALL_STRING_DELIMITERS.has(ch)) stringChar = ch
    result += ch
    i += 1
  }

  return result
}

/**
 * テンプレートリテラル（バッククォート）の中身だけを潰す。
 * 通常クォートは温存するので `import { View } from "react-native"` は読めるままになる。
 */
function maskTemplateLiterals(source) {
  return maskStrings(source, TEMPLATE_DELIMITER_ONLY)
}

/**
 * P029（テンプレートリテラル className 禁止）の例外判定（issue #464）。
 *
 * `className={\`base ${cond ? "a" : "b"}\`}` のように、補間部（`${...}`）が
 * 「文字列リテラルのみで構成される式」（三項・&&・ネスト三項を含む）なら
 * Tailwind の静的クラス抽出を壊さないため対象外にする。`${color}` のような
 * 識別子・関数呼び出し・メンバーアクセスの補間は従来どおり検出する。
 *
 * 文字列一致ベースの簡易パーサーであり、TypeScript の完全な式パーサーではない。
 * 判定に迷うケース（バッククォートのネスト等）は安全側＝「例外にしない」を返す。
 */

/** 文字列/括弧の深さを見ながら、depth 0 の `?` `:` `&&` `||` の位置を集める */
function scanTopLevelOperatorTokens(expr) {
  const tokens = []
  let depth = 0
  let quote = null
  for (let i = 0; i < expr.length; i++) {
    const ch = expr[i]
    if (quote) {
      if (ch === "\\") {
        i += 1
        continue
      }
      if (ch === quote) quote = null
      continue
    }
    if (ch === '"' || ch === "'") {
      quote = ch
      continue
    }
    if (ch === "(" || ch === "[" || ch === "{") {
      depth += 1
      continue
    }
    if (ch === ")" || ch === "]" || ch === "}") {
      depth -= 1
      continue
    }
    if (depth !== 0) continue
    if (ch === "?") tokens.push({ index: i, type: "?" })
    else if (ch === ":") tokens.push({ index: i, type: ":" })
    else if (ch === "&" && expr[i + 1] === "&") {
      tokens.push({ index: i, type: "&&" })
      i += 1
    } else if (ch === "|" && expr[i + 1] === "|") {
      tokens.push({ index: i, type: "||" })
      i += 1
    }
  }
  return tokens
}

/** `cond ? a : b` を depth 0 の `?`/`:` のバランスで分割する（ネスト三項対応） */
function splitTopLevelTernary(expr) {
  const tokens = scanTopLevelOperatorTokens(expr)
  const questionIndex = tokens.findIndex((token) => token.type === "?")
  if (questionIndex === -1) return null
  let balance = 1
  for (let i = questionIndex + 1; i < tokens.length; i++) {
    if (tokens[i].type === "?") balance += 1
    else if (tokens[i].type === ":") {
      balance -= 1
      if (balance === 0) {
        const questionPos = tokens[questionIndex].index
        const colonPos = tokens[i].index
        return {
          whenTrue: expr.slice(questionPos + 1, colonPos),
          whenFalse: expr.slice(colonPos + 1),
        }
      }
    }
  }
  return null
}

/** `lhs && rhs` / `lhs || rhs` を最初の depth 0 演算子で分割する */
function splitTopLevelLogical(expr) {
  const token = scanTopLevelOperatorTokens(expr).find(
    (candidate) => candidate.type === "&&" || candidate.type === "||",
  )
  if (!token) return null
  return { rhs: expr.slice(token.index + token.type.length) }
}

function isStringLiteralExpr(expr) {
  const trimmed = expr.trim()
  return /^"(?:[^"\\]|\\.)*"$/.test(trimmed) || /^'(?:[^'\\]|\\.)*'$/.test(trimmed)
}

/** `(expr)` のように括弧が式全体をちょうど一度だけ包んでいるか */
function isFullyParenWrapped(expr) {
  if (expr[0] !== "(" || expr[expr.length - 1] !== ")") return false
  let depth = 0
  for (let i = 0; i < expr.length; i++) {
    if (expr[i] === "(") depth += 1
    else if (expr[i] === ")") {
      depth -= 1
      if (depth === 0) return i === expr.length - 1
    }
  }
  return false
}

/** 補間式が「文字列リテラルのみで構成される式」か（issue #464） */
export function isLiteralOnlyInterpolation(expr) {
  const trimmed = (expr ?? "").trim()
  if (trimmed === "") return false
  // ネストしたテンプレートリテラルは判定を諦めて安全側（=対象外にしない）に倒す
  if (trimmed.includes("`")) return false
  if (isStringLiteralExpr(trimmed)) return true
  if (isFullyParenWrapped(trimmed)) return isLiteralOnlyInterpolation(trimmed.slice(1, -1))
  const ternary = splitTopLevelTernary(trimmed)
  if (ternary) {
    return isLiteralOnlyInterpolation(ternary.whenTrue) && isLiteralOnlyInterpolation(ternary.whenFalse)
  }
  const logical = splitTopLevelLogical(trimmed)
  if (logical) return isLiteralOnlyInterpolation(logical.rhs)
  return false
}

/** テンプレートリテラル（バッククォート開始位置つき）の中身を取り出す。同一行内で閉じない場合は null */
function extractTemplateLiteralBody(line, backtickIndex) {
  let i = backtickIndex + 1
  let braceDepth = 0
  let content = ""
  while (i < line.length) {
    const ch = line[i]
    if (ch === "\\") {
      content += ch + (line[i + 1] ?? "")
      i += 2
      continue
    }
    if (braceDepth === 0 && ch === "`") return content
    if (ch === "{") braceDepth += 1
    else if (ch === "}" && braceDepth > 0) braceDepth -= 1
    content += ch
    i += 1
  }
  return null
}

/** テンプレートリテラルの中身から `${...}` の中身だけを depth バランスで取り出す */
function extractInterpolationExprs(content) {
  const exprs = []
  let i = content.indexOf("${")
  while (i !== -1) {
    const start = i + 2
    let depth = 1
    let j = start
    while (j < content.length && depth > 0) {
      if (content[j] === "{") depth += 1
      else if (content[j] === "}") depth -= 1
      j += 1
    }
    if (depth === 0) {
      exprs.push(content.slice(start, j - 1))
      i = content.indexOf("${", j)
    } else {
      exprs.push(content.slice(start))
      break
    }
  }
  return exprs
}

/**
 * P029 が fire した行が「className の template literal で、補間部が全て
 * 文字列リテラルのみで構成される式」なら true（＝対象外にしてよい）を返す。
 */
export function isP029TemplateLiteralExempt(line) {
  const classNameIndex = line.indexOf("className=")
  if (classNameIndex === -1) return false
  const backtickIndex = line.indexOf("`", classNameIndex)
  if (backtickIndex === -1) return false
  const content = extractTemplateLiteralBody(line, backtickIndex)
  if (content === null) return false
  const interpolations = extractInterpolationExprs(content)
  if (interpolations.length === 0) return false
  return interpolations.every((expr) => isLiteralOnlyInterpolation(expr))
}

function excludeList(value) {
  return Array.isArray(value) ? value : []
}

/**
 * このファイルは DS パッケージ本体の中にあるか（issue #404）。
 *
 * `excludeDsPaths`（`components/ui/` 等）は「DS 自身の実装なので生タグを書いてよい」
 * という意味の除外なので、consumer が同名ディレクトリ（shadcn 既定の
 * `src/components/ui/`）を持っているだけで効いてはいけない。judgement は
 * 走査対象の実ファイルが DS パッケージ（pkgRoot）配下かどうかで行う。
 */
export function isDsPackageFile(absFile, pkgRoot) {
  if (!pkgRoot || !absFile) return false
  const rel = relative(resolve(pkgRoot), resolve(absFile))
  return rel !== "" && !rel.startsWith("..") && !isAbsolute(rel)
}

/**
 * ルール単位の除外判定（issue #404）。
 *
 * 除外語彙は用途ごとに 3 つに分かれている:
 * - `excludePaths`   … ファイルパスに当てる。どのリポジトリでも効く（`.stories.` 等）
 * - `excludeDsPaths` … ファイルパスに当てるが、**DS パッケージ配下のファイルにだけ**効く
 *                      （`components/ui/` 等。consumer の同名ディレクトリでは効かない）
 * - `excludeLines`   … 行の内容に当てる（`data-slot` / `asChild` / CSS 変数名 等）
 *
 * v1.62.x までは全部が単一の `excludes` に混在し `file.includes || line.includes` の
 * OR で判定していたため、(1) 行内にパス文字列が出るだけでルールが黙り、
 * (2) consumer が `src/components/ui/` に部品を置くと中核 13 ルールが丸ごと無効に
 * なっていた。旧スキーマの `excludes` は後方互換のため従来の OR 判定で引き続き読む。
 */
function matchesRuleExclude(rule, { file, line = "", isDsFile = false }) {
  if (excludeList(rule.excludePaths).some((exclude) => file.includes(exclude))) return true
  if (isDsFile && excludeList(rule.excludeDsPaths).some((exclude) => file.includes(exclude))) {
    return true
  }
  if (excludeList(rule.excludeLines).some((exclude) => line.includes(exclude))) return true
  return excludeList(rule.excludes).some(
    (exclude) => file.includes(exclude) || line.includes(exclude),
  )
}

function shouldIgnorePath(relPath, options) {
  if (!relPath || relPath === ".") return false
  const parts = relPath.split("/")
  if (parts.some((part) => DEFAULT_IGNORES.includes(part))) return true
  if (DEFAULT_IGNORE_PATHS.some((ignored) => relPath.includes(ignored))) return true
  return options.excludes.some((exclude) => relPath.includes(exclude))
}

function summarize(findings) {
  return {
    files: new Set(findings.map((finding) => finding.file)).size,
    errors: findings.filter((finding) => finding.severity === "error").length,
    warnings: findings.filter((finding) => finding.severity !== "error").length,
  }
}

function printText(findings, summary) {
  if (findings.length === 0) {
    console.log("ksk-ds lint: 違反は見つかりませんでした")
    return
  }
  for (const finding of findings) {
    console.log(`${finding.file}:${finding.line} ${finding.severity} ${finding.ruleId} ${finding.message}`)
    if (finding.fix) console.log(`  fix: ${finding.fix}`)
  }
  console.log(
    `\nksk-ds lint: ${summary.errors} error / ${summary.warnings} warning in ${summary.files} files`,
  )
}

function normalize(path) {
  return path.replaceAll("\\", "/")
}
